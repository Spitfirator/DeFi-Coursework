import fs from 'fs';
import path from 'path';

const ARTIFACTS_DIR = path.join(__dirname, '../artifacts/contracts');
const FRONTEND_LIB_DIR = path.join(__dirname, '../pokemon-marketplace-frontend/lib');

const NFT_ARTIFACT_PATH = path.join(ARTIFACTS_DIR, 'PokemonNFT.sol/PokemonNFT.json');
const MARKETPLACE_ARTIFACT_PATH = path.join(ARTIFACTS_DIR, 'PokemonMarketplace.sol/PokemonMarketplace.json');

const OUTPUT_FILE = path.join(FRONTEND_LIB_DIR, 'abis.ts');

async function main() {
    if (!fs.existsSync(FRONTEND_LIB_DIR)) {
        fs.mkdirSync(FRONTEND_LIB_DIR, { recursive: true });
    }

    const nftArtifact = JSON.parse(fs.readFileSync(NFT_ARTIFACT_PATH, 'utf8'));
    const marketplaceArtifact = JSON.parse(fs.readFileSync(MARKETPLACE_ARTIFACT_PATH, 'utf8'));

    const fileContent = `// Generated by scripts/copy_abis.ts
export const PokemonNFTABI = ${JSON.stringify(nftArtifact.abi, null, 2)} as const;

export const PokemonMarketplaceABI = ${JSON.stringify(marketplaceArtifact.abi, null, 2)} as const;
`;

    fs.writeFileSync(OUTPUT_FILE, fileContent);
    console.log(`ABIs written to ${OUTPUT_FILE}`);
}

main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
});
